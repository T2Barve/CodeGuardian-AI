from datetime import datetime, timezone
from typing import Any, Dict, Optional
from fastapi import HTTPException
from pydantic import BaseModel, Field


class ProblemDetail(BaseModel):
    """RFC 7807 problem details specification schema."""

    type: str = Field(
        default="about:blank",
        description="A URI reference that identifies the problem type.",
    )
    title: str = Field(
        ...,
        description="A short, human-readable summary of the problem type.",
    )
    status: int = Field(
        ...,
        description="The HTTP status code generated by the origin server for this occurrence.",
    )
    detail: str = Field(
        ...,
        description="A human-readable explanation specific to this occurrence of the problem.",
    )
    instance: Optional[str] = Field(
        default=None,
        description="A URI reference that identifies the specific occurrence of the problem.",
    )
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="Timestamp when the error occurred.",
    )
    invalid_params: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Optional detailed parameter validation errors.",
    )


class ProblemDetailException(HTTPException):
    """Exception class that renders an RFC 7807 problem details response."""

    def __init__(
        self,
        status_code: int,
        title: str,
        detail: str,
        type_uri: str = "about:blank",
        instance: Optional[str] = None,
        headers: Optional[Dict[str, str]] = None,
    ) -> None:
        super().__init__(status_code=status_code, detail=detail, headers=headers)
        self.title = title
        self.detail = detail
        self.type_uri = type_uri
        self.instance = instance
